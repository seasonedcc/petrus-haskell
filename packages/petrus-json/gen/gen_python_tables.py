#!/usr/bin/env python3
"""Generate CPython's Unicode string tables for ``petrus-json``.

CPython's ``repr(str)`` escapes every character for which ``str.isprintable``
is false, ``str.strip``/``str.split`` use ``str.isspace``, ``str.splitlines``
breaks at the line-boundary characters, and ``int()``/``float()`` read every
Unicode decimal digit (``unicodedata.decimal``). The Petrus and Hamsterdan
references embed such reprs and parse such strings on their wires. GHC's
``Data.Char`` follows the Unicode version GHC ships (15.1 for GHC 9.10), not
the one CPython 3.14 ships (16.0), and its ``isPrint`` also differs in
definition (it admits the space separators). So the predicates are generated
from the pinned interpreter instead, once, for every package.

Run it with the pinned upstream interpreter, from the repository root:

    cd upstream/petrus && uv sync --frozen && cd ../..
    upstream/petrus/.venv/bin/python packages/petrus-json/gen/gen_python_tables.py

It writes two files:

* ``src/Petrus/Json/PythonText/Tables.hs``: the inclusive ranges of
  printable, whitespace and line-boundary code points, and the decimal-digit
  runs, as Haskell literals;
* ``test/python-printable.txt``: the same verdict for every code point
  0..0x10FFFF as alternating runs (the test vector ``PythonTextSpec`` checks
  the Haskell predicate against, code point by code point).
"""

from __future__ import annotations

import hashlib
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "src" / "Petrus" / "Json" / "PythonText" / "Tables.hs"
VECTOR = ROOT / "test" / "python-printable.txt"
MAX = 0x10FFFF


def runs_of(verdicts: list[bool]) -> list[tuple[int, int]]:
    """The inclusive ranges of code points whose verdict is true."""
    ranges: list[tuple[int, int]] = []
    for code, verdict in enumerate(verdicts):
        if not verdict:
            continue
        if ranges and ranges[-1][1] + 1 == code:
            ranges[-1] = (ranges[-1][0], code)
        else:
            ranges.append((code, code))
    return ranges


def literal(name: str, doc: str, ranges: list[tuple[int, int]]) -> list[str]:
    lines = [f"-- | {doc}", f"{name} :: [(Int, Int)]", f"{name} ="]
    for index, (low, high) in enumerate(ranges):
        lead = "  [ " if index == 0 else "  , "
        lines.append(f"{lead}(0x{low:X}, 0x{high:X})")
    lines += ["  ]", ""]
    return lines


def main() -> None:
    assert sys.version_info[:2] == (3, 14), sys.version
    assert unicodedata.unidata_version == "16.0.0", unicodedata.unidata_version
    verdicts = [chr(code).isprintable() for code in range(MAX + 1)]
    bitmap = bytes(1 if verdict else 0 for verdict in verdicts)
    digest = hashlib.sha256(bitmap).hexdigest()

    ranges = runs_of(verdicts)
    spaces = runs_of([chr(code).isspace() for code in range(MAX + 1)])
    breaks = runs_of([len(("a" + chr(code) + "b").splitlines()) == 2 for code in range(MAX + 1)])
    decimals: list[tuple[int, int, int]] = []  # (first code point, length, first value)
    for code in range(MAX + 1):
        value = unicodedata.decimal(chr(code), None)
        if value is None:
            continue
        if decimals:
            low, length, first = decimals[-1]
            if low + length == code and first + length == value:
                decimals[-1] = (low, length + 1, first)
                continue
        decimals.append((code, 1, value))

    version = sys.version.split()[0]
    lines = [
        "-- | GENERATED by gen/gen_python_tables.py -- do not edit.",
        "--",
        f"-- CPython {version} (Unicode {unicodedata.unidata_version}) string tables.",
        f"-- @str.isprintable@: {len(ranges)} ranges, {sum(verdicts)} code points; SHA-256 of",
        f"-- the 0x110000-byte verdict bitmap {digest}.",
        "module Petrus.Json.PythonText.Tables",
        "  ( printableRanges",
        "  , spaceRanges",
        "  , lineBreakRanges",
        "  , decimalRuns",
        "  ) where",
        "",
    ]
    lines += literal("printableRanges", "The inclusive ranges of code points for which @str.isprintable@ holds.", ranges)
    lines += literal("spaceRanges", "The inclusive ranges of code points for which @str.isspace@ holds.", spaces)
    lines += literal("lineBreakRanges", "The inclusive ranges of code points @str.splitlines@ breaks at.", breaks)
    lines += [
        "-- | The decimal digits (@unicodedata.decimal@) as runs: first code point,",
        "-- run length, and the first code point's value.",
        "decimalRuns :: [(Int, Int, Int)]",
        "decimalRuns =",
    ]
    for index, (low, length, first) in enumerate(decimals):
        lead = "  [ " if index == 0 else "  , "
        lines.append(f"{lead}(0x{low:X}, {length}, {first})")
    lines.append("  ]")
    MODULE.parent.mkdir(parents=True, exist_ok=True)
    MODULE.write_text("\n".join(lines) + "\n", encoding="utf-8")

    runs: list[str] = []
    start = 0
    for code in range(1, MAX + 2):
        if code == MAX + 1 or verdicts[code] != verdicts[start]:
            runs.append(f"{start:X} {code - 1:X} {1 if verdicts[start] else 0}")
            start = code
    header = [
        f"# CPython {version} (Unicode {unicodedata.unidata_version}) str.isprintable, every code point 0..10FFFF",
        f"# printable {sum(verdicts)}",
        f"# sha256 {digest}",
        "# runs: first last verdict (hexadecimal code points)",
    ]
    VECTOR.write_text("\n".join(header + runs) + "\n", encoding="utf-8")
    print(f"{len(ranges)} ranges, {sum(verdicts)} printable, {len(runs)} runs, sha256 {digest}")


if __name__ == "__main__":
    main()
