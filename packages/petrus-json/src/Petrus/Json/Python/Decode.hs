-- | CPython's byte decoders, error text for error text: strict
-- @bytes.decode("utf-8")@ with its 'UnicodeDecodeError' message,
-- @bytes.decode("utf-8", "replace")@, and the decoding @json.loads(bytes)@
-- applies (@json.detect_encoding@, then the detected codec with
-- @errors="surrogatepass"@).
--
-- Many Petrus and Hamsterdan refusal texts embed the decoder's message
-- (@'utf-8' codec can't decode byte 0xff in position 3: invalid start byte@),
-- so its classification of the first malformed sequence (start byte,
-- continuation, end of data) and its position range must be CPython's own
-- (@Objects/stringlib/codecs.h@, @Objects/unicodeobject.c@). The test suite
-- compares both functions with the pinned interpreter on generated bytes.
module Petrus.Json.Python.Decode
  ( -- * Strict UTF-8
    decodeUtf8Python
  , utf8DecodeError
  , CodecFailure (..)
  , utf8DecodeFailure
  , decodeFailureText
  , decodeUtf8Replace
    -- * Strict UTF-8 encoding
  , utf8EncodeError
  , utf8EncodeFailure
  , encodeFailureText
    -- * @json.loads(bytes)@
  , detectEncoding
  , decodeJsonBytes
  , jsonBytesFailure
  ) where

import Data.Bits (shiftL, (.&.), (.|.))
import Data.ByteString (ByteString)
import Data.ByteString qualified as BS
import Data.Char (chr, ord)
import Data.Maybe (listToMaybe)
import Data.Text (Text)
import Data.Text qualified as T
import Data.Text.Encoding qualified as TE
import Data.Word (Word8)
import Numeric (showHex)
import Petrus.Json.Wtf8 (fromCodePoints, hasLoneSurrogate)

-- | @payload.decode("utf-8")@ (strict): the text, or the
-- 'UnicodeDecodeError' message CPython reports for the first malformed
-- sequence.
decodeUtf8Python :: ByteString -> Either Text Text
decodeUtf8Python bytes = case TE.decodeUtf8' bytes of
  Right text -> Right text
  Left _ -> Left (maybe "'utf-8' codec can't decode bytes" id (utf8DecodeError bytes))

-- | The 'UnicodeDecodeError' message of strict UTF-8 decoding, or 'Nothing'
-- when the bytes are UTF-8.
utf8DecodeError :: ByteString -> Maybe Text
utf8DecodeError bytes = decodeFailureText bytes <$> utf8DecodeFailure bytes

-- | A 'UnicodeDecodeError''s or 'UnicodeEncodeError''s arguments besides
-- the object: the codec, the offending range @[start, end)@ (bytes when
-- decoding, code points when encoding), and the reason.
data CodecFailure = CodecFailure
  { failureCodec :: Text
  , failureStart :: Int
  , failureEnd :: Int
  , failureReason :: Text
  }
  deriving stock (Eq, Show)

-- | The first malformed sequence strict UTF-8 decoding meets, as CPython's
-- decoder classifies it, or 'Nothing' when the bytes are UTF-8.
utf8DecodeFailure :: ByteString -> Maybe CodecFailure
utf8DecodeFailure bytes
  | BS.isValidUtf8 bytes = Nothing
  | otherwise = either Just (const Nothing) (utf8CodePoints False bytes)

-- | CPython's @UnicodeDecodeError.__str__@ for the bytes decoded: one byte
-- of the object names its value, any other range its first and last
-- positions.
decodeFailureText :: ByteString -> CodecFailure -> Text
decodeFailureText bytes failure
  | failure.failureStart < BS.length bytes && failure.failureEnd - failure.failureStart == 1 =
      "'" <> failure.failureCodec <> "' codec can't decode byte 0x" <> hex2 (BS.index bytes failure.failureStart) <> " in position " <> tshow failure.failureStart <> ": " <> failure.failureReason
  | otherwise =
      "'" <> failure.failureCodec <> "' codec can't decode bytes in position " <> tshow failure.failureStart <> "-" <> tshow (failure.failureEnd - 1) <> ": " <> failure.failureReason

-- | @value.encode("utf-8")@ (strict): 'Nothing' when it succeeds, otherwise
-- the @UnicodeEncodeError@'s @str()@ for the first run of surrogate code
-- points. A 'Text' holds a surrogate only in the WTF-8 form
-- "Petrus.Json.Wtf8" gives a lone surrogate CPython keeps in a @str@.
utf8EncodeError :: Text -> Maybe Text
utf8EncodeError text = encodeFailureText text <$> utf8EncodeFailure text

-- | The first run of surrogates strict UTF-8 encoding refuses, or 'Nothing'
-- when the text encodes.
utf8EncodeFailure :: Text -> Maybe CodecFailure
utf8EncodeFailure text
  | not (hasLoneSurrogate text) = Nothing
  | otherwise =
      let (before, rest) = break isSurrogate (T.unpack text)
          start = length before
          end = start + length (takeWhile isSurrogate rest)
       in Just (CodecFailure "utf-8" start end "surrogates not allowed")
  where
    isSurrogate c = c >= '\xD800' && c <= '\xDFFF'

-- | CPython's @UnicodeEncodeError.__str__@ for the text encoded: one code
-- point of the object names it, any other range its first and last
-- positions.
encodeFailureText :: Text -> CodecFailure -> Text
encodeFailureText text failure
  | failure.failureStart < T.length text && failure.failureEnd - failure.failureStart == 1 =
      "'" <> failure.failureCodec <> "' codec can't encode character '" <> escaped <> "' in position " <> tshow failure.failureStart <> ": " <> failure.failureReason
  | otherwise =
      "'" <> failure.failureCodec <> "' codec can't encode characters in position " <> tshow failure.failureStart <> "-" <> tshow (failure.failureEnd - 1) <> ": " <> failure.failureReason
  where
    code = maybe 0 ord (listToMaybe (drop failure.failureStart (T.unpack text)))
    digits = showHex code ""
    escaped
      | code <= 0xFF = "\\x" <> T.justifyRight 2 '0' (T.pack digits)
      | code <= 0xFFFF = "\\u" <> T.justifyRight 4 '0' (T.pack digits)
      | otherwise = "\\U" <> T.justifyRight 8 '0' (T.pack digits)

codecError :: Text -> Int -> Int -> Text -> Either CodecFailure a
codecError name from to why = Left (CodecFailure name from to why)

hex2 :: Word8 -> Text
hex2 w = let digits = showHex w "" in T.pack (replicate (2 - length digits) '0' ++ digits)

tshow :: Show a => a -> Text
tshow = T.pack . show

-- | CPython's UTF-8 decoder: the code points, or the message for the first
-- malformed sequence. With @surrogatepass@, an encoded surrogate
-- (@ED A0..BF 80..BF@) decodes to its code point.
utf8CodePoints :: Bool -> ByteString -> Either CodecFailure String
utf8CodePoints surrogatePass bytes = go 0
  where
    n = BS.length bytes
    at = BS.index bytes
    cont w = w .&. 0xC0 == 0x80
    low i = fromIntegral (at i) .&. 0x3F :: Int
    go i
      | i >= n = Right []
      | otherwise =
          let b = at i
              remaining = n - i
              bi = fromIntegral b :: Int
           in if
                | b < 0x80 -> (chr bi :) <$> go (i + 1)
                | b < 0xC2 -> invalidStart i
                | b < 0xE0 ->
                    if
                      | remaining < 2 -> endOfData i
                      | not (cont (at (i + 1))) -> invalid i 1
                      | otherwise -> (chr (((bi .&. 0x1F) `shiftL` 6) .|. low (i + 1)) :) <$> go (i + 2)
                | b < 0xF0 ->
                    let decoded = chr (((bi .&. 0x0F) `shiftL` 12) .|. (low (i + 1) `shiftL` 6) .|. low (i + 2))
                     in if
                          | surrogatePass && b == 0xED && remaining >= 3 && at (i + 1) >= 0xA0 && at (i + 1) <= 0xBF && cont (at (i + 2)) ->
                              (decoded :) <$> go (i + 3)
                          | remaining < 3 ->
                              if remaining >= 2 && badSecond3 b (at (i + 1)) then invalid i 1 else endOfData i
                          | badSecond3 b (at (i + 1)) -> invalid i 1
                          | not (cont (at (i + 2))) -> invalid i 2
                          | otherwise -> (decoded :) <$> go (i + 3)
                | b < 0xF5 ->
                    if remaining < 4
                      then
                        if
                          | remaining >= 2 && badSecond4 b (at (i + 1)) -> invalid i 1
                          | remaining >= 3 && not (cont (at (i + 2))) -> invalid i 2
                          | otherwise -> endOfData i
                      else
                        if
                          | badSecond4 b (at (i + 1)) -> invalid i 1
                          | not (cont (at (i + 2))) -> invalid i 2
                          | not (cont (at (i + 3))) -> invalid i 3
                          | otherwise ->
                              ( chr (((bi .&. 0x07) `shiftL` 18) .|. (low (i + 1) `shiftL` 12) .|. (low (i + 2) `shiftL` 6) .|. low (i + 3))
                                  :
                              )
                                <$> go (i + 4)
                | otherwise -> invalidStart i
    badSecond3 b w = not (cont w) || (if w < 0xA0 then b == 0xE0 else b == 0xED)
    badSecond4 b w = not (cont w) || (if w < 0x90 then b == 0xF0 else b == 0xF4)
    invalidStart i = Left (CodecFailure "utf-8" i (i + 1) "invalid start byte")
    invalid i len = Left (CodecFailure "utf-8" i (i + len) "invalid continuation byte")
    endOfData i = Left (CodecFailure "utf-8" i n "unexpected end of data")

-- | @bytes.decode("utf-8", "replace")@: each maximal ill-formed subpart
-- (Unicode §3.9) becomes one U+FFFD, as CPython substitutes; the byte that
-- breaks a sequence is not consumed. @text@'s lenient decoder does not
-- promise this substitution count.
decodeUtf8Replace :: ByteString -> Text
decodeUtf8Replace input
  | BS.isValidUtf8 input = TE.decodeUtf8 input
  | otherwise = T.pack (go 0)
  where
    len = BS.length input
    at = BS.index input
    go i
      | i >= len = []
      | otherwise =
          let b0 = at i
           in if
                | b0 < 0x80 -> chr (fromIntegral b0) : go (i + 1)
                | b0 >= 0xC2 && b0 <= 0xDF -> sequenceOf i b0 [(0x80, 0xBF)]
                | b0 == 0xE0 -> sequenceOf i b0 [(0xA0, 0xBF), (0x80, 0xBF)]
                | b0 == 0xED -> sequenceOf i b0 [(0x80, 0x9F), (0x80, 0xBF)]
                | b0 >= 0xE1 && b0 <= 0xEF -> sequenceOf i b0 [(0x80, 0xBF), (0x80, 0xBF)]
                | b0 == 0xF0 -> sequenceOf i b0 [(0x90, 0xBF), (0x80, 0xBF), (0x80, 0xBF)]
                | b0 >= 0xF1 && b0 <= 0xF3 -> sequenceOf i b0 [(0x80, 0xBF), (0x80, 0xBF), (0x80, 0xBF)]
                | b0 == 0xF4 -> sequenceOf i b0 [(0x80, 0x8F), (0x80, 0xBF), (0x80, 0xBF)]
                | otherwise -> '\xFFFD' : go (i + 1)
    sequenceOf start b0 ranges = continue (start + 1) (leadBits b0 (length ranges)) ranges
    continue i acc [] = chr acc : go i
    continue i acc ((lo, hi) : more)
      | i < len, let b = at i, b >= lo && b <= hi = continue (i + 1) ((acc `shiftL` 6) .|. fromIntegral (b .&. 0x3F)) more
      | otherwise = '\xFFFD' : go i
    leadBits :: Word8 -> Int -> Int
    leadBits b0 = \case
      1 -> fromIntegral (b0 .&. 0x1F)
      2 -> fromIntegral (b0 .&. 0x0F)
      _ -> fromIntegral (b0 .&. 0x07)

-- | @json.detect_encoding(b)@: the codec @json.loads@ decodes bytes with.
detectEncoding :: ByteString -> Text
detectEncoding b
  | BS.isPrefixOf "\x00\x00\xFE\xFF" b || BS.isPrefixOf "\xFF\xFE\x00\x00" b = "utf-32"
  | BS.isPrefixOf "\xFE\xFF" b || BS.isPrefixOf "\xFF\xFE" b = "utf-16"
  | BS.isPrefixOf "\xEF\xBB\xBF" b = "utf-8-sig"
  | BS.length b >= 4 =
      if
        | BS.index b 0 == 0 -> if BS.index b 1 /= 0 then "utf-16-be" else "utf-32-be"
        | BS.index b 1 == 0 -> if BS.index b 2 /= 0 || BS.index b 3 /= 0 then "utf-16-le" else "utf-32-le"
        | otherwise -> "utf-8"
  | BS.length b == 2 =
      if
        | BS.index b 0 == 0 -> "utf-16-be"
        | BS.index b 1 == 0 -> "utf-16-le"
        | otherwise -> "utf-8"
  | otherwise = "utf-8"

-- | @b.decode(json.detect_encoding(b), "surrogatepass")@, the decoding
-- @json.loads(bytes)@ applies: the text (a lone surrogate kept as WTF-8,
-- "Petrus.Json.Wtf8"), or CPython's 'UnicodeDecodeError' message. A
-- signature (BOM) selects its codec and is not part of the text.
decodeJsonBytes :: ByteString -> Either Text Text
decodeJsonBytes b = either (Left . uncurry decodeFailureText) Right (jsonBytesFailure b)

-- | 'decodeJsonBytes' with the 'UnicodeDecodeError''s arguments: the
-- object the codec was given (the bytes, past a UTF-8 signature) and the
-- failure.
jsonBytesFailure :: ByteString -> Either (ByteString, CodecFailure) Text
jsonBytesFailure b = case detectEncoding b of
  -- The signature selects the endian codec, which then names itself in
  -- its errors.
  "utf-32"
    | BS.isPrefixOf "\x00\x00\xFE\xFF" b -> utf32 "utf-32-be" True 4
    | otherwise -> utf32 "utf-32-le" False 4
  "utf-16"
    | BS.isPrefixOf "\xFE\xFF" b -> utf16 "utf-16-be" True 2
    | otherwise -> utf16 "utf-16-le" False 2
  "utf-8-sig" -> utf8 (BS.drop 3 b)
  "utf-16-be" -> utf16 "utf-16-be" True 0
  "utf-16-le" -> utf16 "utf-16-le" False 0
  "utf-32-be" -> utf32 "utf-32-be" True 0
  "utf-32-le" -> utf32 "utf-32-le" False 0
  _ -> utf8 b
  where
    utf8 body = case TE.decodeUtf8' body of
      Right text -> Right text
      Left _ -> either (Left . (body,)) (Right . fromCodePoints) (utf8CodePoints True body)
    utf16 codec bigEndian offset = either (Left . (b,)) (Right . fromCodePoints) (utf16CodePoints codec bigEndian b offset)
    utf32 codec bigEndian offset = either (Left . (b,)) (Right . fromCodePoints) (utf32CodePoints codec bigEndian b offset)

-- | CPython's UTF-16 decoder with @surrogatepass@, from @offset@ (past a
-- signature); error positions count from the start of @whole@.
utf16CodePoints :: Text -> Bool -> ByteString -> Int -> Either CodecFailure String
utf16CodePoints codec bigEndian whole offset = go offset
  where
    len = BS.length whole
    unit i =
      let a = fromIntegral (BS.index whole i) :: Int
          z = fromIntegral (BS.index whole (i + 1)) :: Int
       in if bigEndian then a `shiftL` 8 .|. z else z `shiftL` 8 .|. a
    go i
      | i == len = Right []
      | i + 1 >= len = codecError codec i len "truncated data"
      | otherwise =
          let u = unit i
           in if u >= 0xD800 && u <= 0xDBFF && i + 3 < len && unit (i + 2) >= 0xDC00 && unit (i + 2) <= 0xDFFF
                then (chr (0x10000 + ((u - 0xD800) `shiftL` 10) .|. (unit (i + 2) - 0xDC00)) :) <$> go (i + 4)
                else (chr u :) <$> go (i + 2)

-- | CPython's UTF-32 decoder with @surrogatepass@, as 'utf16CodePoints'.
utf32CodePoints :: Text -> Bool -> ByteString -> Int -> Either CodecFailure String
utf32CodePoints codec bigEndian whole offset = go offset
  where
    len = BS.length whole
    byte i = fromIntegral (BS.index whole i) :: Int
    unit i =
      if bigEndian
        then byte i `shiftL` 24 .|. byte (i + 1) `shiftL` 16 .|. byte (i + 2) `shiftL` 8 .|. byte (i + 3)
        else byte (i + 3) `shiftL` 24 .|. byte (i + 2) `shiftL` 16 .|. byte (i + 1) `shiftL` 8 .|. byte i
    go i
      | i == len = Right []
      | i + 3 >= len = codecError codec i len "truncated data"
      | unit i > 0x10FFFF = codecError codec i (i + 4) "code point not in range(0x110000)"
      | otherwise = (chr (unit i) :) <$> go (i + 4)
