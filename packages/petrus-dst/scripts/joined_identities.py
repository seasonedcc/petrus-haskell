"""Generate the joined worlds' Profile and Checker identities as Haskell.

Every ``ProfileIdentity``/``CheckerIdentity`` constant of the reference's
``tests/dst/joined_*world.py`` modules is read from the module source with
``ast``; the argument of each ``digest_json(...)`` is evaluated in the
imported module's globals, so the Haskell definitions are the reference's
own values (never transcribed by hand). The output is the committed module
``joined/Petrus/Testing/Dst/Joined/Identities.hs``; the Haskell side hashes
each definition with ``digestJson`` exactly as the reference does.

Run from upstream/petrus:

    PYTHONPATH=. uv run --frozen python ../../packages/petrus-dst/scripts/joined_identities.py \
        ../../packages/petrus-dst/joined/Petrus/Testing/Dst/Joined/Identities.hs
"""

from __future__ import annotations

import ast
import importlib
import json
import re
import sys
from pathlib import Path

from petrus.testing.dst import digest_json

MODULES = [
    ("joined_world", "tests.dst.joined_world", ""),
    ("joined_creation_world", "tests.dst.joined_creation_world", "creation"),
    ("joined_registration_world", "tests.dst.joined_registration_world", "registration"),
    ("joined_seal_world", "tests.dst.joined_seal_world", "seal"),
]


def camel(prefix: str, constant: str) -> str:
    words = [w for w in (prefix + "_" + constant).lower().split("_") if w]
    return words[0] + "".join(w.capitalize() for w in words[1:])


def haskell_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=True).replace("\\u", "\\x")


def fix_escapes(literal: str) -> str:
    # json's \uXXXX becomes Haskell's \xXXXX; a following hex digit needs \&.
    return re.sub(r"(\\x[0-9a-fA-F]{4})(?=[0-9a-fA-F])", r"\1\\&", literal)


def json_literal(value, indent: int) -> str:
    pad = " " * indent
    if value is None:
        return "Null"
    if value is True:
        return "Bool True"
    if value is False:
        return "Bool False"
    if isinstance(value, int):
        return f"Int ({value})" if value < 0 else f"Int {value}"
    if isinstance(value, str):
        return f"String {fix_escapes(haskell_string(value))}"
    if isinstance(value, list):
        if not value:
            return "Array []"
        if all(isinstance(item, str) for item in value):
            items = ", ".join(fix_escapes(haskell_string(item)) for item in value)
            return f"strs [{items}]"
        inner = f"\n{pad}  , ".join(json_literal(item, indent + 4) for item in value)
        return f"Array\n{pad}  [ {inner}\n{pad}  ]"
    if isinstance(value, dict):
        if not value:
            return "Object []"
        entries = [
            f"({fix_escapes(haskell_string(key))}, {json_literal(item, indent + 4)})" for key, item in value.items()
        ]
        inner = f"\n{pad}  , ".join(entries)
        return f"Object\n{pad}  [ {inner}\n{pad}  ]"
    raise TypeError(f"unsupported JSON value {value!r}")


def identities(module_file: str, module_name: str, prefix: str):
    module = importlib.import_module(module_name)
    source = Path(module.__file__).read_text(encoding="utf-8")
    tree = ast.parse(source)
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        call = node.value
        if not isinstance(target, ast.Name) or not isinstance(call, ast.Call):
            continue
        if not isinstance(call.func, ast.Name) or call.func.id not in {"ProfileIdentity", "CheckerIdentity"}:
            continue
        keywords = {keyword.arg: keyword.value for keyword in call.keywords}
        digest_call = keywords["digest"]
        assert isinstance(digest_call, ast.Call) and digest_call.func.id == "digest_json"
        definition = eval(compile(ast.Expression(digest_call.args[0]), module_file, "eval"), vars(module))
        live = getattr(module, target.id)
        assert live.digest == digest_json(definition), target.id
        yield target.id, call.func.id, live.name, live.version, definition


def main() -> None:
    out = Path(sys.argv[1])
    lines = [
        "-- | GENERATED by @packages/petrus-dst/scripts/joined_identities.py@ from the",
        "-- pinned reference's @tests/dst/joined_*world.py@: every Profile and Checker",
        "-- identity of the joined worlds, its definition evaluated by the reference",
        "-- itself and hashed here with 'digestJson' exactly as @digest_json@ does.",
        "-- Do not edit by hand; rerun the script.",
        "module Petrus.Testing.Dst.Joined.Identities where",
        "",
        "import Petrus.Json (Json (..))",
        "import Petrus.Testing.Dst (CheckerIdentity, Identity (..), ProfileIdentity)",
        "import Petrus.Testing.Dst.Engine.Common (digestOf, strs)",
    ]
    for module_file, module_name, prefix in MODULES:
        lines += ["", f"-- {module_file}.py"]
        for constant, kind, name, version, definition in identities(module_file, module_name, prefix):
            haskell = camel(prefix, constant)
            hs_type = "ProfileIdentity" if kind == "ProfileIdentity" else "CheckerIdentity"
            lines += [
                "",
                f"-- | @{module_file}.{constant}@.",
                f"{haskell} :: {hs_type}",
                f"{haskell} =",
                "  Identity",
                f"    {{ name = {fix_escapes(haskell_string(name))}",
                f"    , version = {version}",
                "    , digest =",
                "        digestOf",
                f"          ( {json_literal(definition, 12)}",
                "          )",
                "    }",
            ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
