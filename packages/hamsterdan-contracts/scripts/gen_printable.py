"""Generate Hamsterdan.PyLiteral.Printable from the pinned CPython.

    uv run --project upstream/hamsterdan --frozen --python 3.14 \
        python packages/hamsterdan-contracts/scripts/gen_printable.py

CPython's ``repr(str)`` keeps a non-ASCII character verbatim exactly when
``Py_UNICODE_ISPRINTABLE`` (the predicate behind ``str.isprintable``) holds,
and escapes it otherwise. That predicate follows the interpreter's Unicode
database, so the table is generated from the interpreter itself.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "Hamsterdan" / "PyLiteral" / "Printable.hs"


def ranges() -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    start = None
    for code in range(0x80, 0x110000):
        printable = chr(code).isprintable()
        if printable and start is None:
            start = code
        elif not printable and start is not None:
            found.append((start, code - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def main() -> None:
    table = ranges()
    starts = ",".join(f"0x{a:X}" for a, _ in table)
    ends = ",".join(f"0x{b:X}" for _, b in table)
    version = sys.version.split()[0]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        f"""-- | GENERATED by packages/hamsterdan-contracts/scripts/gen_printable.py
-- from CPython {version} (Unicode {unicodedata.unidata_version}). Do not edit by hand.
--
-- The non-ASCII code points CPython's @repr@ keeps verbatim
-- (@Py_UNICODE_ISPRINTABLE@), as sorted, disjoint, inclusive ranges.
module Hamsterdan.PyLiteral.Printable
  ( isPrintableNonAscii
  , unicodeVersion
  ) where

import Data.Array.Unboxed (UArray, bounds, listArray, (!))

-- | The Unicode database version the table was generated from.
unicodeVersion :: String
unicodeVersion = "{unicodedata.unidata_version}"

rangeStarts :: UArray Int Int
rangeStarts = listArray (0, {len(table) - 1}) [{starts}]

rangeEnds :: UArray Int Int
rangeEnds = listArray (0, {len(table) - 1}) [{ends}]

-- | Whether a code point at or above U+0080 is printable for CPython.
isPrintableNonAscii :: Int -> Bool
isPrintableNonAscii code = search 0 (snd (bounds rangeStarts))
  where
    search low high
      | low > high = False
      | otherwise =
          let middle = (low + high) `div` 2
           in if code < rangeStarts ! middle
                then search low (middle - 1)
                else
                  if code > rangeEnds ! middle
                    then search (middle + 1) high
                    else True
"""
    )


if __name__ == "__main__":
    main()
