HEADER = """\
-- | GENERATED by packages/hamsterdan-contracts/scripts/gen_models.py from
-- upstream @{source}@ (see UPSTREAM.md for the pin). Do not edit by hand.
--
-- {doc}
--
-- Every pydantic dataclass becomes a Haskell record and a 'Contract'
-- instance whose codec spells and admits exactly what
-- @TypeAdapter(T).dump_python(mode="json")@ and strict @validate_json@ do.
-- String @Literal@ fields become sum types; single-valued @Literal@ fields
-- (the facts' @kind@, @incarnation: Literal[0]@, ...) carry no information
-- and are therefore not stored, only spelled and checked.
module {module} where

import Data.Text (Text)
{extra_imports}import Hamsterdan.Contracts.Codec
"""


def camel(name: str) -> str:
    if name == "where":
        return "where_"
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in value.split("_"))


class Generator:
    def __init__(self, module_name: str, enums: dict, unions: dict) -> None:
        self.module = importlib.import_module(module_name)
        self.enum_table = enums
        self.union_table = unions
        self.enums: dict[tuple, str] = {}
        self.unions: dict[tuple, str] = {}
        self.decls: list[str] = []
        self.uses_json = False
        # Hedgehog generators (test/Generators/*.hs), one per model and union.
        self.gen_decls: list[str] = []
        self.gen_unions: set[tuple] = set()

    # -- types ---------------------------------------------------------------

    def enum(self, values: tuple) -> tuple[str, str]:
        name, prefix = self.enum_table[values]
        if values not in self.enums:
            ctors = [prefix + pascal(value) for value in values]
            lines = [f"data {name}", "  = " + "\n  | ".join(ctors), "  deriving stock (Eq, Ord, Show, Bounded, Enum)", ""]
            lines += [f"instance Enumeration {name} where", "  spelling = \\case"]
            lines += [f'    {ctor} -> "{value}"' for ctor, value in zip(ctors, values)]
            lines += ["", f"instance Contract {name} where", f'  contract = enumeration "{name}"']
            self.decls.append("\n".join(lines) + "\n")
            self.enums[values] = name
        return name, "contract"

    def union(self, members: tuple[str, ...]) -> tuple[str, str]:
        name, ctors = self.union_table[members]
        if members not in self.unions:
            lines = [f"data {name}", "  = " + "\n  | ".join(f"{c} {m}" for c, m in zip(ctors, members)), "  deriving stock (Eq, Show)", ""]
            lines += [f"instance Contract {name} where", "  contract =", "    union", f'      "{" | ".join(members)}"', "      ( \\case"]
            lines += [f"          {c} value -> encode contract value" for c in ctors]
            lines += ["      )"]
            lines += [("      [ " if i == 0 else "      , ") + f"fmap {c} . decode contract" for i, c in enumerate(ctors)]
            lines += ["      ]"]
            self.decls.append("\n".join(lines) + "\n")
            self.unions[members] = name
        return name, "contract"

    def gen_union(self, members: tuple[str, ...]) -> str:
        name, ctors = self.union_table[members]
        if members not in self.gen_unions:
            alternatives = [f"{c} <$> gen{m}" for c, m in zip(ctors, members)]
            self.gen_decls.append(
                f"gen{name} :: Gen {name}\ngen{name} =\n  Gen.choice\n"
                + "".join(("    [ " if i == 0 else "    , ") + a + "\n" for i, a in enumerate(alternatives))
                + "    ]\n"
            )
            self.gen_unions.add(members)
        return f"gen{name}"

    def gen(self, annotation: str) -> str:
        """The Hedgehog generator of a field annotation (mirrors resolve)."""
        t = annotation.strip()
        simple = {
            "str": "genText",
            "int": "genInteger",
            "bool": "Gen.bool",
            "dict": "genObject",
            "dict[str, Any]": "genObject",
            "tuple[int, int] | tuple[()]": "genPairOrEmpty",
        }
        if t in simple:
            return simple[t]
        if t.endswith(" | None"):
            return f"(Gen.maybe {wrap(self.gen(t[: -len(' | None')]))})"
        if re.fullmatch(r"Literal\[(.*)\]", t, re.S):
            return "Gen.enumBounded"
        if m := re.fullmatch(r"(?:list|tuple)\[(.*?)(?:, \.\.\.)?\]", t):
            return f"(genList {wrap(self.gen(m.group(1)))})"
        if m := re.fullmatch(r"dict\[str, (.*)\]", t):
            return f"(genDict {wrap(self.gen(m.group(1)))})"
        if " | " in t:
            return self.gen_union(tuple(part.strip() for part in t.split(" | ")))
        target = getattr(self.module, t, None)
        if isinstance(target, typing.TypeAliasType):
            return self.gen_union(tuple(arg.__name__ for arg in typing.get_args(target.__value__)))
        if typing.get_origin(target) is typing.Literal:
            return "Gen.enumBounded"
        if isinstance(target, type) and dataclasses.is_dataclass(target):
            return f"gen{t}"
        raise SystemExit(f"unsupported annotation {t!r}")

    def resolve(self, annotation: str) -> tuple[str, str]:
        t = annotation.strip()
        simple = {
            "str": ("Text", "text"),
            "int": ("Integer", "integer"),
            "bool": ("Bool", "bool"),
            "dict": ("Object", "object"),
            "dict[str, Any]": ("Object", "object"),
            "tuple[int, int] | tuple[()]": ("(Maybe (Integer, Integer))", "pairOrEmpty"),
        }
        if t in simple:
            return simple[t]
        if t.endswith(" | None"):
            inner_type, inner_codec = self.resolve(t[: -len(" | None")])
            return f"(Maybe {inner_type})", f"(nullable {wrap(inner_codec)})"
        if m := re.fullmatch(r"Literal\[(.*)\]", t, re.S):
            values = ast.literal_eval("(" + m.group(1) + ",)")
            return self.enum(tuple(values))
        if m := re.fullmatch(r"(?:list|tuple)\[(.*?)(?:, \.\.\.)?\]", t):
            item_type, item_codec = self.resolve(m.group(1))
            return f"[{item_type}]", f"(list {wrap(item_codec)})"
        if m := re.fullmatch(r"dict\[str, (.*)\]", t):
            item_type, item_codec = self.resolve(m.group(1))
            return f"[(Text, {item_type})]", f"(dict {wrap(item_codec)})"
        if " | " in t:
            return self.union(tuple(part.strip() for part in t.split(" | ")))
        target = getattr(self.module, t, None)
        if isinstance(target, typing.TypeAliasType):
            return self.union(tuple(arg.__name__ for arg in typing.get_args(target.__value__)))
        if typing.get_origin(target) is typing.Literal:
            return self.enum(typing.get_args(target))
        if isinstance(target, type) and dataclasses.is_dataclass(target):
            return t, "contract"
        raise SystemExit(f"unsupported annotation {t!r}")

    def default(self, value, hs_type: str, codec: str) -> str:
        if isinstance(value, bool):
            return str(value)
        if isinstance(value, int):
            return str(value)
        if value is None:
            return "Nothing"
        if value == [] or value == {}:
            return "[]"
        if isinstance(value, str):
            for values, name in self.enums.items():
                if name == hs_type:
                    _, prefix = self.enum_table[values]
                    return prefix + pascal(value)
            return '"' + value + '"'
        raise SystemExit(f"unsupported default {value!r}")

    # -- classes -------------------------------------------------------------

    def model(self, name: str, cls: type) -> str:
        record_fields: list[str] = []
        steps: list[str] = []
        positional: list[str] = []
        generators: list[str] = []
        applied = False
        for f in dataclasses.fields(cls):
            annotation = str(f.type)
            if f.default is not dataclasses.MISSING:
                default = f.default
                has_default = True
            elif f.default_factory is not dataclasses.MISSING:
                default = f.default_factory()
                has_default = True
            else:
                default = None
                has_default = False
            index = len(positional)
            if m := re.fullmatch(r"Literal\[(.*)\]", annotation):
                values = ast.literal_eval("(" + m.group(1) + ",)")
                if len(values) == 1:
                    (only,) = values
                    spelled = f'(String "{only}")' if isinstance(only, str) else f"(Int {only})"
                    self.uses_json = True
                    combinator = "constFieldDefault" if has_default else "constField"
                    steps.append(f'{"<*" if applied else "<$"} {combinator} "{f.name}" {spelled}')
                    positional.append(f'{"<*" if applied else "<$"} memberConst "{f.name}" {spelled} v{index}')
                    applied = True
                    continue
            hs_type, codec = self.resolve(annotation)
            generators.append(self.gen(annotation))
            record_fields.append(f"{camel(f.name)} :: {hs_type}")
            operator = "<*>" if steps else "<$>"
            if has_default:
                steps.append(
                    f'{operator} fieldDefault "{f.name}" (.{camel(f.name)}) {self.default(default, hs_type, codec)} {codec}'
                )
            else:
                steps.append(f'{operator} field "{f.name}" (.{camel(f.name)}) {codec}')
            positional.append(f'{operator} member "{f.name}" {wrap(codec)} v{index}')
            applied = True
        if record_fields:
            data = f"data {name} = {name}\n  {{ " + "\n  , ".join(record_fields) + "\n  }\n  deriving stock (Eq, Show)\n"
        else:
            data = f"data {name} = {name}\n  deriving stock (Eq, Show)\n"
        if steps:
            pattern = "[" + ", ".join(f"(_, v{i})" for i in range(len(positional))) + "]"
            body = (
                f'    recordWith "{name}" positional $\n      {name}\n'
                + "".join(f"        {s}\n" for s in steps)
                + "    where\n"
                + "      positional = \\case\n"
                + f"        {pattern} ->\n"
                + f"          Just $\n            {name}\n"
                + "".join(f"              {s}\n" for s in positional)
                + "        _ -> Nothing\n"
            )
        else:
            body = f'    record "{name}" (pure {name})\n'
        built = f"{name}\n    <$> " + "\n    <*> ".join(generators) if generators else f"pure {name}"
        settle = GEN_SPECIAL.get(name)
        if settle:
            built = f"{settle} <$> ({built})"
        self.gen_decls.append(f"gen{name} :: Gen {name}\ngen{name} =\n  {built}\n")
        wrapper = SPECIAL.get(name)
        if wrapper:
            indented = "".join("  " + line + "\n" for line in body.splitlines())
            instance = f"instance Contract {name} where\n  contract =\n    {wrapper[0]} $\n{indented}"
            return data + "\n" + instance + "\n" + wrapper[1]
        return data + "\n" + f"instance Contract {name} where\n  contract =\n{body}"

    def render(self, module: str, source: str, doc: str) -> str:
        models = []
        names = []
        for name, cls in vars(self.module).items():
            if isinstance(cls, type) and dataclasses.is_dataclass(cls) and cls.__module__ == self.module.__name__:
                models.append(self.model(name, cls))
                names.append(name)
        registry = (
            "-- | Every model of the module, in declaration order.\n"
            "models :: [Model]\n"
            "models =\n"
            + "".join(("  [ " if i == 0 else "  , ") + f"modelOf (contract @{n})\n" for i, n in enumerate(names))
            + "  ]\n"
        )
        extra = "import Petrus.Json (Json (..))\n" if self.uses_json else ""
        if module.endswith(".Readiness"):
            extra = "import Data.Text qualified as T\n" + extra
        out = HEADER.format(module=module, source=source, doc=doc, extra_imports=extra)
        out += "\n" + "\n".join(models) + "\n-- * Literal enumerations and unions\n\n" + "\n".join(self.decls) + "\n" + registry
        self.model_names = names
        return out

    def render_generators(self, module: str, source_module: str) -> str:
        """The test module of Hedgehog generators, one per model and union,
        and the round-trip property of every model (render must run first)."""
        properties = (
            "-- | @validate . dump == Right@ for every model, in declaration order.\n"
            "roundTrips :: [(String, Property)]\n"
            "roundTrips =\n"
            + "".join(
                ("  [ " if i == 0 else "  , ") + f'("{n}", roundTrip gen{n})\n' for i, n in enumerate(self.model_names)
            )
            + "  ]\n"
        )
        return GEN_HEADER.format(module=module, source=source_module) + "\n" + "\n".join(self.gen_decls) + "\n" + properties


def wrap(codec: str) -> str:
    return codec if codec.startswith("(") or " " not in codec else f"({codec})"


SPECIAL = {
    # ActionsObservation.__post_init__ fills an empty observation with
    # "{run_id}:{attempt}:{conclusion}"; no instance ever holds "".
    "ActionsObservation": (
        "normalizing settleObservation",
        """
-- | @ActionsObservation.__post_init__@: an empty @observation@ becomes
-- @"{run_id}:{attempt}:{conclusion}"@, so no observation is ever empty.
settleObservation :: ActionsObservation -> ActionsObservation
settleObservation value
  | T.null value.observation =
      ActionsObservation
        { epoch = value.epoch
        , head = value.head
        , runId = value.runId
        , attempt = value.attempt
        , conclusion = value.conclusion
        , fingerprint = value.fingerprint
        , capabilityAvailable = value.capabilityAvailable
        , observation = value.runId <> ":" <> T.pack (show value.attempt) <> ":" <> spelling value.conclusion
        , operation = value.operation
        , baseHead = value.baseHead
        , policyDigest = value.policyDigest
        }
  | otherwise = value
""",
    ),
}


